def _fft_len(n):
    size = 1
    while size < n:
        size <<= 1
    return size


def spectral_shape(x, cutoff_hz, shelf_db, hp_hz=28.0, order=2):
    """Zero-phase tone shaping: high-pass, high shelf, gentle low-pass.

    Done in the frequency domain rather than as an IIR loop because a per-sample
    Python filter over a few million samples is unusably slow, and because a
    zero-phase curve keeps the pad's transients where they were.
    """
    n = x.shape[-1]
    pad = int(0.25 * SR)
    size = _fft_len(n + pad)
    spec = np.fft.rfft(x, size, axis=-1)
    freq = np.fft.rfftfreq(size, 1.0 / SR)
    safe = np.maximum(freq, 1e-6)

    hp = 1.0 / np.sqrt(1.0 + (hp_hz / safe) ** 4)
    lp = 1.0 / np.sqrt(1.0 + (safe / max(cutoff_hz, 50.0)) ** (2 * order))
    shelf_start = 1800.0
    span = np.clip(np.log2(safe / shelf_start) / 2.0, 0.0, 1.0)
    shelf = 10.0 ** ((shelf_db / 20.0) * span)

    curve = hp * lp * shelf
    curve[0] = 0.0
    out = np.fft.irfft(spec * curve, size, axis=-1)
    return out[..., :n]


def fft_convolve(x, h):
    """Convolve ``x`` (n,) with ``h`` (m,), truncated back to n samples."""
    n = x.shape[-1]
    m = h.shape[-1]
    size = _fft_len(n + m)
    y = np.fft.irfft(np.fft.rfft(x, size) * np.fft.rfft(h, size), size)
    return y[:n]


def make_reverb_ir(rng, decay_sec, predelay_ms=22.0):
    """Stereo impulse response: decorrelated noise under an exponential decay."""
    n = max(1, int(SR * decay_sec))
    t = np.arange(n, dtype=np.float64) / SR
    env = np.exp(-6.9 * t / max(decay_sec, 1e-3))
    ir = rng.standard_normal((2, n)) * env
    # a short fade-in stops the burst reading as a click at the reverb onset
    fade = min(n, int(0.006 * SR))
    if fade:
        ir[:, :fade] *= np.linspace(0.0, 1.0, fade)
    pre = int(SR * predelay_ms / 1000.0)
    out = np.zeros((2, n + pre), dtype=np.float64)
    out[:, pre:] = ir
    out = spectral_shape(out, 2600.0, -6.0, hp_hz=90.0)
    norm = np.sqrt(np.sum(out ** 2, axis=1, keepdims=True))
    norm[norm < 1e-12] = 1.0
    return out / norm


def haas(stereo, samples):
    """Delay the right channel by ``samples`` for width. Zero-filled, not rolled."""
    if samples <= 0:
        return stereo
    out = stereo.copy()
    out[1] = np.concatenate((np.zeros(samples), stereo[1][:-samples]))
    return out


def set_width(stereo, width):
    """Mid/side width control.

    Independent per-channel pad phases plus a Haas delay produce a very wide
    image, and a wide image partially cancels when a phone or a LinkedIn player
    sums it to mono. Pulling the side channel back to 0.72 keeps the width
    audible on headphones and keeps the bed intact in mono.
    """
    mid = 0.5 * (stereo[0] + stereo[1])
    side = 0.5 * (stereo[0] - stereo[1]) * width
    return np.vstack((mid + side, mid - side))


def db_to_lin(db):
    return 10.0 ** (float(db) / 20.0)


