def which(name):
    found = shutil.which(name)
    if not found:
        raise MusicError(
            "%s is not on PATH. Install it (brew install ffmpeg) and retry." % name)
    return found


def run(cmd, label, timeout=600):
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          timeout=timeout)
    if proc.returncode != 0:
        tail = proc.stderr.decode("utf-8", "replace").strip().splitlines()[-12:]
        raise MusicError("%s failed (exit %d):\n  %s"
                         % (label, proc.returncode, "\n  ".join(tail)))
    return proc


def measure_loudness(ffmpeg, path, target_i, target_tp):
    """First loudnorm pass. Returns the measured values as strings, or None."""
    proc = subprocess.run(
        [ffmpeg, "-nostdin", "-hide_banner", "-i", path,
         "-af", "loudnorm=I=%0.2f:TP=%0.2f:LRA=%0.2f:print_format=json"
                % (target_i, target_tp, LOUDNORM_LRA),
         "-f", "null", "-"],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=600)
    text = proc.stderr.decode("utf-8", "replace")
    start = text.rfind("{")
    end = text.rfind("}")
    if start < 0 or end < start:
        return None
    try:
        return json.loads(text[start:end + 1])
    except ValueError:
        return None


def loudnorm_filter(target_i, target_tp, measured):
    """Two-pass (linear) loudnorm when a measurement is available.

    Single-pass loudnorm runs a look-ahead limiter that eats the tail of a short
    bed and moves the duration. The linear second pass is a static gain plus a
    limiter, so the sample count is untouched -- which is what makes the exact
    duration guarantee hold.
    """
    base = "loudnorm=I=%0.2f:TP=%0.2f:LRA=%0.2f" % (target_i, target_tp, LOUDNORM_LRA)
    if not measured:
        return base
    try:
        return (base + ":measured_I=%s:measured_TP=%s:measured_LRA=%s"
                       ":measured_thresh=%s:offset=%s:linear=true:print_format=summary"
                % (measured["input_i"], measured["input_tp"], measured["input_lra"],
                   measured["input_thresh"], measured["target_offset"]))
    except KeyError:
        return base


def probe_duration(ffprobe, path):
    proc = subprocess.run(
        [ffprobe, "-v", "error", "-show_entries", "format=duration",
         "-of", "default=nw=1:nk=1", path],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60)
    try:
        return float(proc.stdout.decode("utf-8", "replace").strip())
    except ValueError:
        return None


def encode(ffmpeg, src, dest, target_i, measured, duration):
    """Master ``src`` to ``dest``, honouring the extension, at exact duration."""
    ext = os.path.splitext(dest)[1].lower()
    cmd = [ffmpeg, "-nostdin", "-hide_banner", "-y",
           "-fflags", "+bitexact", "-i", src,
           "-af", loudnorm_filter(target_i, TARGET_TRUE_PEAK_DB, measured),
           "-ar", str(SR), "-ac", str(CHANNELS),
           "-t", "%.6f" % duration,
           "-map_metadata", "-1"]
    if ext in (".wav", ""):
        cmd += ["-c:a", "pcm_s16le", "-flags:a", "+bitexact", "-bitexact"]
    elif ext in (".m4a", ".mp4", ".aac"):
        cmd += ["-c:a", "aac", "-b:a", "192k", "-movflags", "+faststart"]
    elif ext == ".mp3":
        cmd += ["-c:a", "libmp3lame", "-b:a", "192k"]
    elif ext == ".flac":
        cmd += ["-c:a", "flac"]
    else:
        raise MusicError(
            "unsupported output extension %r. Use .wav (default), .m4a, .mp3 or .flac."
            % ext)
    cmd.append(dest)
    run(cmd, "ffmpeg (master)")


