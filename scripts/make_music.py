def plan_bars(duration, bpm):
    """Choose a bar count, then adjust the tempo so bars land exactly on ``duration``.

    Truncating the last phrase to hit a duration is what makes generated music
    sound generated. Nudging the tempo by a percent or two is inaudible.
    """
    bars = int(round(duration * float(bpm) / 240.0))
    bars = max(2, bars)
    bpm_eff = 240.0 * bars / duration
    return bars, bpm_eff


def allocate_sections(structure, bars):
    """Split ``bars`` across the requested sections, at least one bar each."""
    sections = list(structure)
    while len(sections) > bars:
        for name in SECTION_DROP_ORDER:
            if name in sections and len(sections) > bars:
                sections.remove(name)
                break
        else:
            sections = sections[:bars]
    weights = [SECTION_WEIGHT.get(s, 1.0) for s in sections]
    total = sum(weights) or 1.0
    raw = [bars * w / total for w in weights]
    counts = [max(1, int(math.floor(v))) for v in raw]
    # hand the remainder out by largest fractional part, deterministically
    while sum(counts) > bars:
        order = sorted(range(len(counts)), key=lambda i: (-counts[i], i))
        for i in order:
            if counts[i] > 1:
                counts[i] -= 1
                break
        else:
            break
    remainder = bars - sum(counts)
    fracs = sorted(range(len(raw)), key=lambda i: (-(raw[i] - math.floor(raw[i])), i))
    i = 0
    while remainder > 0 and fracs:
        counts[fracs[i % len(fracs)]] += 1
        remainder -= 1
        i += 1
    return sections, counts


def build_bar_plan(sections, counts, degrees, bars):
    """One entry per bar: which chord, which elements are audible, at what level."""
    plan = []
    bar = 0
    for name, count in zip(sections, counts):
        spec = SECTIONS[name]
        for j in range(count):
            half = count // 2
            def on(flag):
                if flag == "late":
                    return j >= half
                return bool(flag)
            elements = {
                "pad": on(spec["pad"]),
                "sub": on(spec["sub"]),
                "arp": on(spec["arp"]),
                "perc": on(spec["perc"]),
            }
            if spec["taper"]:
                # elements fall away towards the end of the outro
                elements["arp"] = j < max(0, count - 2)
                elements["perc"] = j < max(0, count - 2)
                if j == count - 1:
                    elements["sub"] = True
            degree = degrees[bar % len(degrees)]
            if bar == bars - 1:
                degree = 0  # resolve to the root on the final bar
            plan.append({
                "bar": bar,
                "section": name,
                "degree": degree,
                "level": spec["level"],
                "arpScale": spec["arpScale"],
                "elements": elements,
                "isLast": bar == bars - 1,
            })
            bar += 1
    return plan


