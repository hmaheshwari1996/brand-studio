def render_stems(preset, tonic_pc, scale, bar_plan, bar_sec, n_total, rng):
    """Render the four dry mono stems. Returns {name: float64 array}."""
    stems = {
        "pad": np.zeros((2, n_total), dtype=np.float64),
        "bass": np.zeros(n_total, dtype=np.float64),
        "arp": np.zeros(n_total, dtype=np.float64),
        "perc": np.zeros(n_total, dtype=np.float64),
    }
    bar_n = int(round(bar_sec * SR))
    pad_phases_l = rng.random(64) * 2.0 * np.pi
    pad_phases_r = rng.random(64) * 2.0 * np.pi
    detune = preset["detuneCents"]
    vib_hz = preset["vibratoHz"]
    vib_depth = preset["vibratoDepth"]

    for entry in bar_plan:
        start = entry["bar"] * bar_n
        degree = entry["degree"]
        level = entry["level"]
        last = entry["isLast"]

        # --- pad -----------------------------------------------------------
        if entry["elements"]["pad"]:
            release = 2.6 if last else 0.9
            note_n = min(n_total - start, bar_n + int(release * SR))
            if note_n > 0:
                env = adsr(note_n,
                           attack=0.55 if entry["section"] == "intro" else 0.30,
                           decay=0.35, sustain=0.88, release=release)
                for midi in voiced_chord(48, tonic_pc, scale, degree):
                    freq = midi_to_freq(midi)
                    left = voice_pad(freq, note_n, pad_phases_l, detune, vib_hz, vib_depth)
                    right = voice_pad(freq, note_n, pad_phases_r, detune, vib_hz, vib_depth)
                    stems["pad"][0, start:start + note_n] += left * env * level
                    stems["pad"][1, start:start + note_n] += right * env * level

        # --- sub -----------------------------------------------------------
        if entry["elements"]["sub"]:
            release = 1.6 if last else 0.45
            note_n = min(n_total - start, bar_n + int(release * SR))
            if note_n > 0:
                env = adsr(note_n, attack=0.06, decay=0.25, sustain=0.85,
                           release=release, smooth_attack=False)
                root_midi = voiced_chord(24, tonic_pc, scale, degree)[0]
                stems["bass"][start:start + note_n] += \
                    voice_sub(midi_to_freq(root_midi), note_n, float(rng.random()) * 6.283) \
                    * env * level

        # --- arpeggio ------------------------------------------------------
        if entry["elements"]["arp"] and not last:
            density = min(0.95, preset["arpDensity"] * entry["arpScale"])
            chord = voiced_chord(72, tonic_pc, scale, degree)
            pool = []
            for octave in range(preset["arpOctaves"]):
                pool.extend([m + 12 * octave for m in chord])
            eighth_n = bar_n // 8
            hits = rng.random(8) < density
            hits[0] = True  # always mark the downbeat so the bar has a shape
            step = 0
            for slot in range(8):
                if not hits[slot]:
                    continue
                pos = start + slot * eighth_n
                decay = 0.85
                note_n = min(n_total - pos, int((decay + 0.35) * SR))
                if note_n <= 0:
                    continue
                midi = pool[step % len(pool)]
                step += 1
                gain = 1.0 if slot % 2 == 0 else 0.62
                stems["arp"][pos:pos + note_n] += voice_bell(
                    midi_to_freq(midi), note_n, float(rng.random()) * 6.283, decay
                ) * gain * level

        # --- percussion ----------------------------------------------------
        style = preset["perc"]
        if entry["elements"]["perc"] and style and not last:
            quarter_n = bar_n // 4
            if "kick" in style:
                for beat in (0, 2):
                    pos = start + beat * quarter_n
                    note_n = min(n_total - pos, int(0.45 * SR))
                    if note_n > 0:
                        stems["perc"][pos:pos + note_n] += voice_kick(note_n) * level
            eighth_n = bar_n // 8
            for slot in (1, 3, 5, 7):
                if rng.random() > 0.72:
                    continue
                pos = start + slot * eighth_n
                note_n = min(n_total - pos, int(0.28 * SR))
                if note_n > 0:
                    stems["perc"][pos:pos + note_n] += \
                        voice_brush(note_n, rng) * level * 0.55
    return stems


def process_stem(name, mono_or_stereo, preset, ir):
    """Tone-shape, reverb and widen one stem. Returns a (2, n) array."""
    if mono_or_stereo.ndim == 1:
        stereo = np.vstack((mono_or_stereo, mono_or_stereo))
    else:
        stereo = mono_or_stereo

    cutoff, shelf, high_pass = preset["cutoffHz"], preset["shelfDb"], 28.0
    if name == "bass":
        # the sub has no business above 400 Hz, and nothing below 40 Hz survives
        # a laptop speaker while it does eat headroom
        cutoff, shelf, high_pass = 420.0, -12.0, 40.0
    elif name == "perc":
        cutoff, shelf, high_pass = 6200.0, -2.0, 60.0   # brushes keep some air
    elif name == "pad":
        high_pass = 55.0                                # leave the bottom to the sub
    stereo = spectral_shape(stereo, cutoff, shelf, hp_hz=high_pass)

    wet_amount = preset["reverbMix"].get(
        {"pad": "pad", "bass": "sub", "arp": "arp", "perc": "perc"}[name], 0.0)
    if wet_amount > 0.0:
        wet = np.vstack((fft_convolve(stereo[0], ir[0]),
                         fft_convolve(stereo[1], ir[1])))
        stereo = (1.0 - wet_amount) * stereo + wet_amount * wet

    if name in ("pad", "arp"):
        stereo = set_width(haas(stereo, HAAS_SAMPLES), STEREO_WIDTH)
    return stereo


def apply_fades(buf, fade_in, fade_out):
    n = buf.shape[-1]
    ni = min(n, int(round(fade_in * SR)))
    no = min(n, int(round(fade_out * SR)))
    if ni > 0:
        ramp = np.linspace(0.0, 1.0, ni, endpoint=False)
        buf[:, :ni] *= (0.5 - 0.5 * np.cos(np.pi * ramp))
    if no > 0:
        ramp = np.linspace(0.0, 1.0, no, endpoint=True)
        buf[:, n - no:] *= (0.5 + 0.5 * np.cos(np.pi * ramp))
    return buf


def write_wav(path, stereo):
    """Write a (2, n) float array as 16-bit PCM. No metadata, so it is stable."""
    clipped = np.clip(stereo, -1.0, 1.0)
    interleaved = np.empty(clipped.shape[1] * 2, dtype=np.float64)
    interleaved[0::2] = clipped[0]
    interleaved[1::2] = clipped[1]
    pcm = np.round(interleaved * 32767.0).astype("<i2")
    directory = os.path.dirname(os.path.abspath(path))
    if directory and not os.path.isdir(directory):
        os.makedirs(directory)
    handle = wave.open(path, "wb")
    try:
        handle.setnchannels(CHANNELS)
        handle.setsampwidth(2)
        handle.setframerate(SR)
        handle.writeframes(pcm.tobytes())
    finally:
        handle.close()


