def main(argv=None):
    args = parse_args(argv if argv is not None else sys.argv[1:])

    if args.list_moods:
        print_moods()
        return 0

    if args.duration is None:
        raise MusicError("--duration is required (seconds). Try --list-moods to browse presets.")
    duration = float(args.duration)
    if duration < 2.0:
        raise MusicError("--duration must be at least 2 seconds; got %.3f" % duration)
    if duration > 900.0:
        raise MusicError("--duration above 900s is almost certainly a mistake; got %.1f" % duration)

    ffmpeg = which("ffmpeg")
    ffprobe = which("ffprobe")

    brand_id = args.brand or default_brand_id()
    try:
        music_cfg, brand_id = load_music_config(brand_id)
    except brandlib.BrandNotFound as exc:
        raise MusicError(str(exc))

    if args.mood:
        mood, mood_reason = args.mood, "requested with --mood"
    else:
        mood, mood_reason = mood_from_brand(music_cfg)
    preset = dict(MOODS[mood])
    preset["levels"] = dict(preset["levels"])
    preset["reverbMix"] = dict(preset["reverbMix"])

    mode_name = args.mode or preset["mode"]
    scale = MODES[mode_name]
    key_name = args.key or preset["key"]
    tonic_pc = note_to_pc(key_name)
    bpm_requested = float(args.bpm) if args.bpm else float(preset["bpm"])
    if bpm_requested < 30.0 or bpm_requested > 200.0:
        raise MusicError("--bpm must be between 30 and 200; got %.1f" % bpm_requested)

    target_lufs = args.lufs
    if target_lufs is None:
        try:
            target_lufs = float(music_cfg.get("targetLufs", DEFAULT_TARGET_LUFS))
        except (TypeError, ValueError):
            target_lufs = DEFAULT_TARGET_LUFS

    def _fade(key, fallback):
        try:
            value = float(music_cfg.get(key, fallback))
        except (TypeError, ValueError):
            return fallback
        return value if value >= 0.0 else fallback
    fade_in = min(_fade("fadeInSec", DEFAULT_FADE_IN), duration * 0.4)
    fade_out = min(_fade("fadeOutSec", DEFAULT_FADE_OUT), duration * 0.5)

    structure = DEFAULT_STRUCTURE
    if args.structure:
        structure = [s.strip().lower() for s in args.structure.split(",") if s.strip()]
        unknown = [s for s in structure if s not in SECTIONS]
        if unknown:
            raise MusicError("unknown structure section(s) %s. Known: %s"
                             % (", ".join(unknown), ", ".join(sorted(SECTIONS))))
        if not structure:
            raise MusicError("--structure was empty")

    out = args.out or "bed.wav"
    out = os.path.abspath(out)

    # ---- compose ---------------------------------------------------------
    degrees, degree_swaps = sanitise_degrees(scale, preset["degrees"])
    preset["degrees"] = degrees

    bars, bpm_eff = plan_bars(duration, bpm_requested)
    bar_sec = duration / bars
    sections, counts = allocate_sections(structure, bars)
    bar_plan = build_bar_plan(sections, counts, degrees, bars)

    rng = np.random.default_rng(int(args.seed))
    n_samples = int(round(duration * SR))
    n_total = n_samples + int(TAIL_SEC * SR)

    stems = render_stems(preset, tonic_pc, scale, bar_plan, bar_sec, n_total, rng)
    ir = make_reverb_ir(rng, preset["reverbSec"])

    processed = {}
    for name in ("pad", "bass", "arp", "perc"):
        processed[name] = process_stem(name, stems[name], preset, ir)[:, :n_samples]
        del stems[name]

    mix = np.zeros((2, n_samples), dtype=np.float64)
    for buf in processed.values():
        mix += buf

    peak = float(np.max(np.abs(mix)))
    gain = db_to_lin(PREMASTER_PEAK_DBFS) / peak if peak > 1e-9 else 1.0
    mix *= gain
    apply_fades(mix, fade_in, fade_out)

    # ---- master ----------------------------------------------------------
    work = os.path.join(os.path.expanduser("~"), ".cache", "brand-studio", "tmp")
    if not os.path.isdir(work):
        os.makedirs(work)
    premaster = os.path.join(work, "make_music_premaster.wav")
    write_wav(premaster, mix)

    measured = measure_loudness(ffmpeg, premaster, target_lufs, TARGET_TRUE_PEAK_DB)
    encode(ffmpeg, premaster, out, target_lufs, measured, duration)

    stem_paths = {}
    if args.stems:
        # The same static gain goes on every stem, so the stems sum back to the
        # master and a human can rebalance them without re-levelling anything.
        stem_gain_db = 0.0
        if measured:
            try:
                stem_gain_db = min(
                    target_lufs - float(measured["input_i"]),
                    TARGET_TRUE_PEAK_DB - float(measured["input_tp"]))
            except (KeyError, ValueError):
                stem_gain_db = 0.0
        base, ext = os.path.splitext(out)
        for name in ("pad", "bass", "arp", "perc"):
            buf = processed[name] * gain
            apply_fades(buf, fade_in, fade_out)
            raw = os.path.join(work, "make_music_stem_%s.wav" % name)
            write_wav(raw, buf * db_to_lin(stem_gain_db))
            dest = "%s.%s%s" % (base, name, ext if ext else ".wav")
            run([ffmpeg, "-nostdin", "-hide_banner", "-y", "-fflags", "+bitexact",
                 "-i", raw, "-t", "%.6f" % duration, "-map_metadata", "-1",
                 "-c:a", "pcm_s16le", "-flags:a", "+bitexact", "-bitexact",
                 os.path.splitext(dest)[0] + ".wav"],
                "ffmpeg (stem %s)" % name)
            stem_paths[name] = os.path.splitext(dest)[0] + ".wav"
            os.remove(raw)
    del processed
    if os.path.isfile(premaster):
        os.remove(premaster)

    # ---- verify ----------------------------------------------------------
    actual = probe_duration(ffprobe, out)
    final = measure_loudness(ffmpeg, out, target_lufs, TARGET_TRUE_PEAK_DB) or {}

    def _f(key):
        try:
            return round(float(final[key]), 2)
        except (KeyError, TypeError, ValueError):
            return None

    flats = prefers_flats(tonic_pc, mode_name, key_name)
    numerals = [roman_numeral(scale, d) for d in preset["degrees"]]
    chords = [chord_name(tonic_pc, scale, d, flats) for d in preset["degrees"]]

    structure_map = []
    cursor = 0
    for name, count in zip(sections, counts):
        entries = bar_plan[cursor:cursor + count]
        active = sorted(set(k for e in entries for k, v in e["elements"].items() if v))
        structure_map.append({
            "section": name,
            "bars": count,
            "startSec": round(cursor * bar_sec, 3),
            "endSec": round((cursor + count) * bar_sec, 3),
            "elements": active,
            "chords": [chord_name(tonic_pc, scale, e["degree"], flats) for e in entries],
            "note": SECTIONS[name]["note"],
        })
        cursor += count

    error_ms = None if actual is None else round(abs(actual - duration) * 1000.0, 1)
    sidecar = {
        "generator": "brand-studio/scripts/make_music.py",
        "copyright": ("Procedurally synthesised from music theory. No samples, no "
                      "loop library and no trained model were used, so the output "
                      "is original and unencumbered. It is an underscore bed, not "
                      "a produced track."),
        "brand": brand_id,
        "mood": mood,
        "moodReason": mood_reason,
        "moodBlurb": preset["blurb"],
        "key": spell(tonic_pc, flats),
        "mode": mode_name,
        "timeSignature": "4/4",
        "bpm": round(bpm_eff, 3),
        "bpmRequested": round(bpm_requested, 3),
        "bpmAdjustedPct": round((bpm_eff / bpm_requested - 1.0) * 100.0, 2),
        "bars": bars,
        "barSeconds": round(bar_sec, 4),
        "progression": {
            "degrees": list(preset["degrees"]),
            "romanNumerals": numerals,
            "chords": chords,
            "asWritten": "%s  (%s)" % (" - ".join(numerals), " ".join(chords)),
            "substitutions": degree_swaps or None,
        },
        "structure": structure_map,
        "seed": int(args.seed),
        "duration": {
            "requestedSec": round(duration, 4),
            "actualSec": None if actual is None else round(actual, 4),
            "errorMs": error_ms,
        },
        "loudness": {
            "targetLufs": round(float(target_lufs), 2),
            "measuredLufs": _f("input_i"),
            "truePeakDb": _f("input_tp"),
            "lra": _f("input_lra"),
            "truePeakCeilingDb": TARGET_TRUE_PEAK_DB,
        },
        "fade": {"inSec": round(fade_in, 3), "outSec": round(fade_out, 3)},
        "synthesis": {
            "sampleRate": SR,
            "channels": CHANNELS,
            "levels": preset["levels"],
            "arpDensity": preset["arpDensity"],
            "arpOctaves": preset["arpOctaves"],
            "percussion": preset["perc"],
            "reverbSec": preset["reverbSec"],
            "reverbMix": preset["reverbMix"],
            "cutoffHz": preset["cutoffHz"],
            "shelfDb": preset["shelfDb"],
            "detuneCents": preset["detuneCents"],
            "vibratoHz": preset["vibratoHz"],
            "haasSamples": HAAS_SAMPLES,
            "stereoWidth": STEREO_WIDTH,
        },
        "files": {"audio": out, "stems": stem_paths or None},
        "command": "make_music.py " + " ".join(argv if argv is not None else sys.argv[1:]),
    }

    sidecar_path = out + ".music.json"
    with open(sidecar_path, "w") as handle:
        json.dump(sidecar, handle, indent=2, sort_keys=False)
        handle.write("\n")
    sidecar["files"]["sidecar"] = sidecar_path

    if args.json:
        print(json.dumps(sidecar, indent=2))
    else:
        print("wrote    %s" % out)
        print("sidecar  %s" % sidecar_path)
        print("mood     %s  (%s)" % (mood, mood_reason))
        print("music    %s %s, %.1f bpm, %d bars x %.3fs, %s"
              % (spell(tonic_pc, flats), mode_name, bpm_eff, bars, bar_sec,
                 sidecar["progression"]["asWritten"]))
        print("form     %s" % " -> ".join("%s(%d)" % (s["section"], s["bars"])
                                          for s in structure_map))
        print("duration %.3fs requested, %.3fs actual (%s ms off)"
              % (duration, actual if actual is not None else float("nan"),
                 "?" if error_ms is None else error_ms))
        print("loudness %s LUFS (target %.1f), true peak %s dBTP"
              % (sidecar["loudness"]["measuredLufs"], target_lufs,
                 sidecar["loudness"]["truePeakDb"]))
        for name, path in sorted(stem_paths.items()):
            print("stem     %-5s %s" % (name, path))

    if error_ms is not None and error_ms > 50.0:
        sys.stderr.write(
            "WARNING: duration is %.1f ms off the request; the container "
            "may be padding.\n" % error_ms)

    if args.preview:
        player = shutil.which("afplay") or shutil.which("ffplay")
        if not player:
            sys.stderr.write("no afplay or ffplay on PATH; skipping --preview\n")
        else:
            cmd = [player, out] if player.endswith("afplay") else \
                [player, "-autoexit", "-nodisp", "-loglevel", "error", out]
            subprocess.call(cmd, timeout=duration + 20)

    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except MusicError as exc:
        sys.stderr.write("make_music.py: %s\n" % exc)
        sys.exit(2)
    except KeyboardInterrupt:
        sys.stderr.write("\ninterrupted\n")
        sys.exit(130)
