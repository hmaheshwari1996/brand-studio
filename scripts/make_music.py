"""make_music.py - generate a copyright-free music bed for a brand film.

WHY THIS IS COPYRIGHT-FREE
--------------------------
There is no music model here and no music API. Every sample is SYNTHESISED FROM
SCRATCH out of music theory: a key, a mode, a chord progression, and additive
synthesis voices built from sine partials. Nothing is sampled, nothing is looped
from a library, and no model trained on recorded music is involved at any point.
The output is a mathematical function of (mood, key, mode, bpm, seed, duration).
That is what makes it genuinely clearable -- the person who runs this owns the
result outright, with no licence, no attribution and no rights-holder anywhere.

WHAT IT IS NOT
--------------
This is an UNDERSCORE BED, not a produced track. There are no real instruments,
no performance, no drummer and no arrangement beyond four voices moving through
a chord progression. It is designed to sit *underneath* narration and give a
film a floor -- which is exactly what a corporate film needs and roughly all it
needs. Put it in front of an audience on its own and it will sound like what it
is: a tasteful synth pad. If a film needs a hook, a melody someone hums, or live
players, licence a real track. This will not get you there and pretending
otherwise wastes a client's time.

HOW IT WORKS
------------
44.1 kHz stereo, numpy, written with the stdlib ``wave`` module, mastered with
ffmpeg ``loudnorm``.

  voices    pad   5 harmonics, plus two copies detuned +/-7 cents, slow vibrato
            bell  inharmonic partials at 1 / 2.76 / 5.4 with exponential decay
            sub   fundamental + octave (+ a trace of the twelfth)
            perc  soft kick from a pitch-swept sine, brushes from filtered noise
  envelope  per-note ADSR, raised-cosine attack on the pad
  space     reverb by FFT convolution with an exponentially-decaying seeded
            noise burst; Haas widening (one channel delayed ~220 samples)
  tone      zero-phase spectral shaping: 28 Hz high-pass, high shelf, gentle
            low-pass, so the bed stays under narration instead of fighting it
  form      a real arc -- intro / build / hold / outro -- not four bars looped

Usage:
    make_music.py --duration 30 --mood confident --out bed.wav --json
    make_music.py --duration 45 --brand example --out bed.wav --stems
    make_music.py --duration 20 --key D --mode dorian --bpm 72 --out bed.m4a
    make_music.py --list-moods

Every run writes a sidecar ``<out>.music.json`` describing exactly what was
played, so a bed can be regenerated byte-for-byte or explained to a client.
"""

