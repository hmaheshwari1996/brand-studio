def default_brand_id():
    try:
        brands = brandlib.list_brands()
    except Exception:
        return None
    return brands[0]["id"] if len(brands) == 1 else None


def load_music_config(brand_id):
    """Return (music_dict, brand_id_or_None). Never raises for a missing brand."""
    if not brand_id:
        return {}, None
    brand = brandlib.load_brand(brand_id)
    video = brand.get("video") or {}
    music = video.get("music") or {}
    return music, brand.get("id", brand_id)


def mood_from_brand(music):
    """Pick a default mood consistent with the brand's own mood/avoid arrays."""
    wanted = [str(m).strip().lower() for m in (music.get("mood") or [])]
    avoid = [str(a).strip().lower() for a in (music.get("avoid") or [])]

    scores = dict((m, 0.0) for m in MOOD_ORDER)
    for word in wanted:
        hit = BRAND_MOOD_HINTS.get(word)
        if hit:
            scores[hit] += 2.0
        else:
            for token in word.replace("-", " ").split():
                hit = BRAND_MOOD_HINTS.get(token)
                if hit:
                    scores[hit] += 1.0
    for mood in MOOD_ORDER:
        for veto in MOOD_VETOES.get(mood, ()):
            if any(veto in a for a in avoid):
                scores[mood] -= 5.0
    best = max(MOOD_ORDER, key=lambda m: (scores[m], -MOOD_ORDER.index(m)))
    if scores[best] <= 0.0:
        return "confident", "no usable brand mood hints; falling back to 'confident'"
    reason = "brand video.music.mood %s -> %s" % (json.dumps(wanted), best)
    if avoid:
        reason += "; avoiding %s" % json.dumps(avoid)
    return best, reason


