def note_to_pc(name):
    """'A' / 'Bb' / 'F#' -> pitch class 0..11."""
    raw = str(name).strip().replace("♯", "#").replace("♭", "b")
    key = raw.upper()
    if key in NOTE_ALIASES:
        key = NOTE_ALIASES[key]
    if key in NOTE_NAMES:
        return NOTE_NAMES.index(key)
    raise MusicError(
        "unknown key %r. Use one of: %s (flats accepted: Bb, Eb, Ab, Db, Gb)"
        % (name, ", ".join(NOTE_NAMES)))


def midi_to_freq(midi):
    return 440.0 * (2.0 ** ((float(midi) - 69.0) / 12.0))


def triad(scale, degree):
    """Semitone offsets of the diatonic triad rooted on ``degree``."""
    n = len(scale)
    out = []
    for step in (0, 2, 4):
        idx = degree + step
        out.append(scale[idx % n] + 12 * (idx // n))
    return out


def triad_quality(intervals):
    third = intervals[1] - intervals[0]
    fifth = intervals[2] - intervals[0]
    if third == 3 and fifth == 7:
        return "min"
    if third == 4 and fifth == 7:
        return "maj"
    if third == 3 and fifth == 6:
        return "dim"
    if third == 4 and fifth == 8:
        return "aug"
    return "maj" if third >= 4 else "min"


def roman_numeral(scale, degree):
    """Roman numeral relative to the *mode's own* scale.

    In A minor that gives i - VI - III - VII for Am F C G, which is how a
    musician would write it, rather than the parallel-major i - bVI - bIII - bVII.
    """
    quality = triad_quality(triad(scale, degree))
    base = ROMAN[degree % 7]
    if quality in ("min", "dim"):
        base = base.lower()
    if quality == "dim":
        base += "°"
    elif quality == "aug":
        base += "+"
    return base


def prefers_flats(tonic_pc, mode_name, raw_key=None):
    """Whether to spell this key with flats. Honours what the user typed."""
    if raw_key:
        text = str(raw_key).strip().replace("♭", "b").replace("♯", "#")
        if len(text) > 1 and text[1] == "b":
            return True
        if len(text) > 1 and text[1] == "#":
            return False
    if mode_name in ("major", "lydian"):
        return tonic_pc in FLAT_TONICS_MAJOR
    return tonic_pc in FLAT_TONICS_MINOR


def spell(pitch_class, flats):
    return (FLAT_NAMES if flats else NOTE_NAMES)[pitch_class % 12]


def chord_name(tonic_pc, scale, degree, flats=False):
    root_pc = (tonic_pc + scale[degree % len(scale)]) % 12
    quality = triad_quality(triad(scale, degree))
    suffix = {"min": "m", "maj": "", "dim": "dim", "aug": "aug"}[quality]
    return spell(root_pc, flats) + suffix


def sanitise_degrees(scale, degrees):
    """Swap out diminished/augmented triads a mode override can introduce.

    Each mood's progression is chosen for its own mode. Forcing a different mode
    with --mode can land a degree on a diminished triad -- vii° in major, #iv° in
    lydian -- which is unstable and reads as a mistake under narration. Dropping
    that degree a third lands on a consonant chord in every supported mode.
    Returns (degrees, substitutions).
    """
    out = []
    swaps = []
    for degree in degrees:
        quality = triad_quality(triad(scale, degree))
        if quality in ("dim", "aug"):
            replacement = (degree - 2) % len(scale)
            swaps.append({"from": ROMAN[degree % 7], "to": ROMAN[replacement % 7],
                          "why": "%s triad is unstable under narration" % quality})
            out.append(replacement)
        else:
            out.append(degree)
    return out, swaps


def voiced_chord(base_midi, tonic_pc, scale, degree):
    """Absolute MIDI notes for the triad, inverted to stay near ``base_midi``.

    Rooting every chord at the same octave makes the progression leap around;
    folding roots above the tritone down an octave gives the smooth, mostly
    stepwise motion a bed wants.
    """
    intervals = triad(scale, degree)
    offset = intervals[0] % 12
    if offset > 6:
        offset -= 12
    root = base_midi + tonic_pc + offset
    return [root, root + (intervals[1] - intervals[0]),
            root + (intervals[2] - intervals[0])]


