def adsr(n, attack, decay, sustain, release, smooth_attack=True):
    """Per-note amplitude envelope of ``n`` samples."""
    env = np.zeros(n, dtype=np.float64)
    if n <= 0:
        return env
    na = min(int(round(attack * SR)), n)
    nd = min(int(round(decay * SR)), n - na)
    nr = min(int(round(release * SR)), n - na - nd)
    ns = n - na - nd - nr
    i = 0
    if na:
        ramp = np.linspace(0.0, 1.0, na, endpoint=False)
        env[:na] = 0.5 - 0.5 * np.cos(np.pi * ramp) if smooth_attack else ramp
        i = na
    if nd:
        env[i:i + nd] = np.linspace(1.0, sustain, nd, endpoint=False)
        i += nd
    if ns:
        env[i:i + ns] = sustain
        i += ns
    if nr:
        tail = np.linspace(1.0, 0.0, nr, endpoint=True)
        env[i:i + nr] = sustain * (tail ** 1.6)
    return env


def voice_pad(freq, n, phases, detune_cents, vib_hz, vib_depth):
    """Five harmonics, three detuned copies, slow shared vibrato."""
    t = np.arange(n, dtype=np.float64) / SR
    out = np.zeros(n, dtype=np.float64)
    harmonics = ((1, 1.00), (2, 0.42), (3, 0.21), (4, 0.11), (5, 0.065))
    idx = 0
    for cents in (0.0, detune_cents, -detune_cents):
        f0 = freq * (2.0 ** (cents / 1200.0))
        # frequency-modulation index for a vibrato of +/- vib_depth * f0
        index = (vib_depth * f0) / max(vib_hz, 1e-6)
        vib = index * np.sin(2.0 * np.pi * vib_hz * t + phases[idx % len(phases)])
        idx += 1
        for k, amp in harmonics:
            ph = phases[idx % len(phases)]
            idx += 1
            out += amp * np.sin(2.0 * np.pi * f0 * k * t + k * vib + ph)
    return out / 4.6


def voice_bell(freq, n, phase, decay_sec):
    """Inharmonic partials at 1 / 2.76 / 5.4, each decaying exponentially."""
    t = np.arange(n, dtype=np.float64) / SR
    out = np.zeros(n, dtype=np.float64)
    for ratio, amp, rate in ((1.00, 1.00, 1.0), (2.76, 0.42, 1.9), (5.40, 0.19, 3.1)):
        out += amp * np.exp(-rate * t / max(decay_sec, 1e-3)) * \
            np.sin(2.0 * np.pi * freq * ratio * t + phase * ratio)
    return out / 1.61


def voice_sub(freq, n, phase):
    """Fundamental plus octave, with a trace of the twelfth for definition.

    The octave carries about half the weight of the fundamental. A pure sine
    root reads as rumble on a laptop speaker and as mud in a phone mix; the
    octave is what makes the bass line audible where the film is actually
    watched.
    """
    t = np.arange(n, dtype=np.float64) / SR
    return (0.85 * np.sin(2.0 * np.pi * freq * t + phase)
            + 0.45 * np.sin(2.0 * np.pi * freq * 2.0 * t + phase)
            + 0.08 * np.sin(2.0 * np.pi * freq * 3.0 * t)) / 1.38


def voice_kick(n):
    """Soft kick: a sine swept 110 Hz -> 46 Hz with a short exponential decay."""
    t = np.arange(n, dtype=np.float64) / SR
    freq = 46.0 + 64.0 * np.exp(-t / 0.035)
    phase = 2.0 * np.pi * np.cumsum(freq) / SR
    return np.sin(phase) * np.exp(-t / 0.155)


def voice_brush(n, rng):
    """Brush: white noise tilted upward twice, then an 60 ms decay."""
    x = rng.standard_normal(n)
    for _ in range(2):
        x = x - 0.88 * np.concatenate(([0.0], x[:-1]))
    t = np.arange(n, dtype=np.float64) / SR
    env = np.exp(-t / 0.055)
    fade = min(n, int(0.003 * SR))
    if fade:
        env[:fade] *= np.linspace(0.0, 1.0, fade)
    return x * env * 0.35


